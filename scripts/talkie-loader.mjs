// @ts-check
// Writes the loading screen into index.html as one pixel-art SVG image, so it is on the very first paint: no script,
// no font, no request. The talkie waits with its mouth shut ("hmm", src/modules/room/tour/talkie-frames.ts) under a
// pixel speech bubble in which three dots bounce in turn, like "typing..." in a messenger; when the room is ready the
// talkie's real bubble says hello.
//
// Everything is drawn on one pixel grid: each run of same-coloured pixels on a row becomes a 1-pixel-high rectangle
// in one path per colour; the dots are rectangles of their own that the SVG's CSS moves. It is an <img> of a data URL,
// not inline SVG: an image counts as the page's content for Largest Contentful Paint, inline SVG does not.
//
//   node scripts/talkie-loader.mjs          rewrite the image between the markers in index.html
//   node scripts/talkie-loader.mjs --check  exit 1 if index.html is out of date (for CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FRAMES_TS = join(ROOT, 'src/modules/room/tour/talkie-frames.ts');
const INDEX = join(ROOT, 'index.html');
const START = '<!-- talkie-loader:start (generated by scripts/talkie-loader.mjs) -->';
const END = '<!-- talkie-loader:end -->';
/** CSS pixels per art pixel: an even scale keeps the image's size even, so the page centres it on whole pixels */
const SCALE = 4;
const INK = '#0c0c10';
const PAPER = '#ffffff';

/**
 * A mouth frame, cropped to its drawn pixels.
 * @param {string} name
 * @returns {{ w: number, h: number, at: (x: number, y: number) => string | null }}
 */
function mouth(name) {
  const src = readFileSync(FRAMES_TS, 'utf8');
  const m = new RegExp(`${name}: 'data:image/png;base64,([^']+)'`).exec(src);
  if (!m?.[1]) throw new Error(`no ${name} frame in talkie-frames.ts`);
  const png = PNG.sync.read(Buffer.from(m[1], 'base64'));
  /** @param {number} x @param {number} y */
  const px = (x, y) => {
    const o = (y * png.width + x) * 4;
    if (!png.data[o + 3]) return null;
    return '#' + [0, 1, 2].map((k) => (png.data[o + k] ?? 0).toString(16).padStart(2, '0')).join('');
  };
  let x0 = png.width;
  let y0 = png.height;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < png.height; y++)
    for (let x = 0; x < png.width; x++)
      if (px(x, y)) {
        x0 = Math.min(x0, x);
        y0 = Math.min(y0, y);
        x1 = Math.max(x1, x);
        y1 = Math.max(y1, y);
      }
  return { w: x1 - x0 + 1, h: y1 - y0 + 1, at: (x, y) => px(x + x0, y + y0) };
}

/**
 * A grid of colours (null = transparent) with drawing helpers.
 * @param {number} w
 * @param {number} h
 */
function grid(w, h) {
  /** @type {(string | null)[][]} */
  const cells = Array.from({ length: h }, () => Array.from({ length: w }, () => null));
  /** @param {number} x @param {number} y @param {string} c */
  const set = (x, y, c) => {
    const row = cells[y];
    if (row && x >= 0 && x < w) row[x] = c;
  };
  /** @param {number} x @param {number} y @param {number} rw @param {number} rh @param {string} c */
  const rect = (x, y, rw, rh, c) => {
    for (let j = 0; j < rh; j++) for (let i = 0; i < rw; i++) set(x + i, y + j, c);
  };
  /** one path per colour, a rectangle per run */
  const paths = () => {
    /** @type {Map<string, string[]>} */
    const by = new Map();
    cells.forEach((row, y) => {
      for (let x = 0; x < w;) {
        const c = row[x];
        if (!c) {
          x++;
          continue;
        }
        let n = 1;
        while (x + n < w && row[x + n] === c) n++;
        const runs = by.get(c) ?? [];
        runs.push(`M${String(x)} ${String(y)}h${String(n)}v1h-${String(n)}z`);
        by.set(c, runs);
        x += n;
      }
    });
    return [...by].map(([c, runs]) => `<path fill="${c}" d="${runs.join('')}"/>`).join('');
  };
  return { set, rect, paths };
}

function loader() {
  const shut = mouth('hmm');
  // the bubble: a white box with a 1-pixel ink frame, its corners cut, and a stepped tail down to the mouth
  const BW = 31; // bubble width
  const BH = 13; // bubble height
  const TAIL = 2;
  const GAP = 3; // between the tail and the mouth
  const W = Math.max(BW + 2, shut.w);
  const bx = Math.floor((W - BW) / 2);
  const H = BH + TAIL + GAP + shut.h;
  const g = grid(W, H);
  g.rect(bx + 1, 1, BW - 2, BH - 2, PAPER);
  g.rect(bx + 1, 0, BW - 2, 1, INK);
  g.rect(bx + 1, BH - 1, BW - 2, 1, INK);
  g.rect(bx, 1, 1, BH - 2, INK);
  g.rect(bx + BW - 1, 1, 1, BH - 2, INK);
  const cx = bx + Math.floor(BW / 2);
  g.rect(cx - 1, BH - 1, 2, 1, PAPER); // the tail opens the frame...
  g.set(cx - 2, BH, INK);
  g.rect(cx - 1, BH, 2, 1, PAPER);
  g.set(cx + 1, BH, INK);
  g.rect(cx - 1, BH + 1, 2, 1, INK); // ...and closes in a point
  const my = BH + TAIL + GAP;
  const mx = Math.floor((W - shut.w) / 2);
  for (let y = 0; y < shut.h; y++)
    for (let x = 0; x < shut.w; x++) {
      const c = shut.at(x, y);
      if (c) g.set(mx + x, my + y, c);
    }
  // three 3x3 dots, 3 pixels apart, centred in the bubble
  const DOT = 3;
  const dy = Math.floor((BH - DOT) / 2);
  const dots = [-6, 0, 6].map(
    (off, i) =>
      `<rect class="d d${String(i)}" x="${String(cx + off - 1)}" y="${String(dy)}" width="${String(DOT)}" height="${String(DOT)}" fill="${INK}"/>`,
  );
  // each dot hops 2 pixels, then 1, then rests, a sixth of the cycle after the one before; pixel steps, no easing
  const css =
    `.d{animation:h 1.2s steps(1) infinite}.d1{animation-delay:.2s}.d2{animation-delay:.4s}` +
    `@keyframes h{0%{transform:translateY(0)}15%{transform:translateY(-2px)}30%{transform:translateY(-1px)}45%,100%{transform:translateY(0)}}` +
    `@media (prefers-reduced-motion:reduce){.d{animation:none}}`;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(W)} ${String(H)}" shape-rendering="crispEdges">` +
    `<style>${css}</style>${g.paths()}${dots.join('')}</svg>`;
  const url =
    'data:image/svg+xml,' +
    svg.replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/"/g, "'");
  return `<img class="talkie-loader" src="${url}" width="${String(W * SCALE)}" height="${String(H * SCALE)}" alt="">`;
}

const img = loader();
const html = readFileSync(INDEX, 'utf8');
const a = html.indexOf(START);
const b = html.indexOf(END);
if (a < 0 || b < a) throw new Error(`index.html has no ${START} ... ${END} markers`);
const next = html.slice(0, a + START.length) + img + html.slice(b);
if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('index.html: the talkie loader is out of date; run node scripts/talkie-loader.mjs');
    process.exitCode = 1;
  }
} else {
  writeFileSync(INDEX, next);
  console.log(`index.html: talkie loader written (${String(img.length)} bytes)`);
}
