// @ts-check
// Writes the loading screen's talking mouth into index.html as pixel-art SVG, so it is on the very first paint: no
// script, no font, no request. The frames are the talkie's own (src/modules/room/tour/talkie-frames.ts, 64x31 PNG
// data URLs): each run of same-coloured pixels on a row becomes a 1-pixel-high rectangle in one path per colour, the
// frames are laid side by side in a strip, and the SVG's own CSS steps through it. It is an <img> of a data URL, not
// inline SVG: an image counts as the page's content for Largest Contentful Paint, inline SVG does not.
//
//   node scripts/talkie-loader.mjs          rewrite the SVG between the markers in index.html
//   node scripts/talkie-loader.mjs --check  exit 1 if index.html is out of date (for CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FRAMES_TS = join(ROOT, 'src/modules/room/tour/talkie-frames.ts');
const INDEX = join(ROOT, 'index.html');
const START = '<!-- talkie-loader:start (generated by scripts/talkie-loader.mjs) -->';
const END = '<!-- talkie-loader:end -->';
/** the strip: the grin first (shown when motion is reduced), then the speaking frames the CSS steps through */
const STRIP = ['idle', 'aaa', 'ooo', 'thhh', 'uhh', 'aaa', 'hmm'];

/** @returns {Record<string, PNG>} */
function readFrames() {
  const src = readFileSync(FRAMES_TS, 'utf8');
  /** @type {Record<string, PNG>} */
  const out = {};
  for (const [, name, b64] of src.matchAll(/(\w+): 'data:image\/png;base64,([^']+)'/g))
    out[name] = PNG.sync.read(Buffer.from(b64, 'base64'));
  return out;
}

/** One path per colour: every horizontal run of that colour as `M x y h w v1 h-w z`. */
function strip(frames) {
  /** @type {Map<string, string[]>} */
  const byColour = new Map();
  const first = frames[STRIP[0]];
  if (!first) throw new Error('no idle frame');
  const { width: W, height: H } = first;
  STRIP.forEach((name, i) => {
    const png = frames[name];
    if (!png) throw new Error(`no frame ${name}`);
    for (let y = 0; y < H; y++) {
      let x = 0;
      while (x < W) {
        const o = (y * W + x) * 4;
        const a = png.data[o + 3];
        if (!a) {
          x++;
          continue;
        }
        const hex = '#' + [0, 1, 2].map((k) => png.data[o + k].toString(16).padStart(2, '0')).join('');
        let w = 1;
        while (x + w < W) {
          const q = (y * W + x + w) * 4;
          const same = png.data[q + 3] && [0, 1, 2].every((k) => png.data[q + k] === png.data[o + k]);
          if (!same) break;
          w++;
        }
        const runs = byColour.get(hex) ?? [];
        runs.push(`M${String(i * W + x)} ${String(y)}h${String(w)}v1h-${String(w)}z`);
        byColour.set(hex, runs);
        x += w;
      }
    }
  });
  const paths = [...byColour].map(([hex, runs]) => `<path fill="${hex}" d="${runs.join('')}"/>`).join('');
  const steps = STRIP.length - 1;
  // the grin (frame 0) when motion is reduced; otherwise the speaking frames 1..n, one every 110 ms like the talkie
  const css =
    `g{transform:translateX(-${String(W)}px);animation:t ${String(steps * 0.11)}s steps(${String(steps)}) infinite}` +
    `@keyframes t{from{transform:translateX(-${String(W)}px)}to{transform:translateX(-${String(W * (steps + 1))}px)}}` +
    `@media (prefers-reduced-motion:reduce){g{animation:none;transform:none}}`;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(W)} ${String(H)}" shape-rendering="crispEdges">` +
    `<style>${css}</style><g>${paths}</g></svg>`;
  const url =
    'data:image/svg+xml,' +
    svg.replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/"/g, "'");
  return `<img class="talkie-loader" src="${url}" width="${String(W * 3)}" height="${String(H * 3)}" alt="">`;
}

const svg = strip(readFrames());
const html = readFileSync(INDEX, 'utf8');
const a = html.indexOf(START);
const b = html.indexOf(END);
if (a < 0 || b < a) throw new Error(`index.html has no ${START} ... ${END} markers`);
const next = html.slice(0, a + START.length) + svg + html.slice(b);
if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('index.html: the talkie loader is out of date; run node scripts/talkie-loader.mjs');
    process.exitCode = 1;
  }
} else {
  writeFileSync(INDEX, next);
  console.log(`index.html: talkie loader written (${String(svg.length)} bytes)`);
}
