export type StringKey = keyof typeof T;

/** The string for the desktop's current language; `%s` takes the argument. */
export function L(key: StringKey, arg?: string | number): string {
  return format(S.lang === 'en' ? T[key].en : T[key].ru, arg);
}

/** Text (plain or bilingual) in the desktop's current language. */
export function tr(text: Text | null | undefined): string {
  return trLang(text, S.lang);
}
